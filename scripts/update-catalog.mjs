// Build-time only. The extension never contacts Wikidata while browsing.
import { writeFile, rename, rm } from "node:fs/promises";

// QLever's public Wikidata mirror handles the full catalog query efficiently.
const endpoint = "https://qlever.dev/api/wikidata";
const prefixes = `
PREFIX wd: <http://www.wikidata.org/entity/>
PREFIX wdt: <http://www.wikidata.org/prop/direct/>
PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>
PREFIX skos: <http://www.w3.org/2004/02/skos/core#>`;

async function query(sparql) {
  const response = await fetch(endpoint, {
    method: "POST",
    body: new URLSearchParams({ query: prefixes + sparql }),
    headers: {
      Accept: "application/sparql-results+json",
      "Content-Type": "application/x-www-form-urlencoded",
      "User-Agent": "StreamingRegionalFilter/1.2 (https://github.com/apoorvdarshan/streaming-indian-filter)"
    },
    signal: AbortSignal.timeout(90000)
  });
  if (!response.ok) throw new Error(`Wikidata returned HTTP ${response.status}: ${(await response.text()).slice(0, 500)}`);
  return (await response.json()).results.bindings;
}

export function normalize(text) {
  return text.normalize("NFKD").replace(/\p{M}/gu, "").toLowerCase()
    .replace(/&/g, " and ").replace(/[^\p{L}\p{N}]+/gu, " ").trim();
}

const entries = new Map();
const works = new Set();
console.log("Fetching production years…");
const dateRows = await query(`SELECT ?work ?year WHERE {
  ?work wdt:P495 wd:Q668; (wdt:P577|wdt:P580) ?date.
  BIND(YEAR(?date) AS ?year)
}`);
const yearsByWork = new Map();
for (const row of dateRows) {
  if (!row.year || !Number.isInteger(Number(row.year.value))) continue;
  if (!yearsByWork.has(row.work.value)) yearsByWork.set(row.work.value, new Set());
  yearsByWork.get(row.work.value).add(Number(row.year.value));
}
for (const [kind, name] of [["Q11424", "films"], ["Q5398426", "TV series"], ["Q526877", "web series"]]) {
  console.log(`Fetching Indian ${name}…`);
  const types = await query(`SELECT DISTINCT ?type WHERE {
    ?type wdt:P279* wd:${kind}.
    ?production wdt:P31 ?type; wdt:P495 wd:Q668.
  }`);
  console.log(`${types.length} production types`);
  const rows = [];
  // Small batches avoid service-side sorts over large intermediate joins.
  for (let offset = 0; offset < types.length; offset += 30) {
    const values = types.slice(offset, offset + 30).map(row => `<${row.type.value}>`).join(" ");
    rows.push(...await query(`SELECT ?work ?title WHERE {
    VALUES ?type { ${values} }
    ?work wdt:P495 wd:Q668; wdt:P31 ?type;
      (rdfs:label|skos:altLabel|wdt:P1476) ?title.
    FILTER(LANG(?title) IN ("en", ""))
  }`));
    console.log(`  ${Math.min(offset + 30, types.length)}/${types.length} types`);
  }
  for (const row of rows) {
    const title = normalize(row.title.value);
    if (!title || /^q\d+$/.test(title)) continue;
    works.add(row.work.value);
    if (!entries.has(title)) entries.set(title, new Set());
    for (const year of yearsByWork.get(row.work.value) || []) entries.get(title).add(year);
  }
  console.log(`${rows.length} title/year records`);
}
if (works.size < 10000) throw new Error("Catalog unexpectedly small; keeping the previous snapshot.");

// A shared English name alone is not evidence of Indian origin. The popup's
// safer option preserves these collisions unless explicit origin is available.
console.log("Finding titles shared with non-Indian productions…");
const collisions = await query(`SELECT DISTINCT ?title WHERE {
  { SELECT DISTINCT ?title WHERE {
    VALUES ?kind { wd:Q11424 wd:Q5398426 wd:Q526877 }
    ?indian wdt:P495 wd:Q668; wdt:P31/wdt:P279* ?kind; rdfs:label ?title.
    FILTER(LANG(?title) = "en")
  } }
  ?other rdfs:label ?title; wdt:P495 ?country.
  FILTER(?country != wd:Q668)
  FILTER NOT EXISTS { ?other wdt:P495 wd:Q668 }
  VALUES ?type { wd:Q11424 wd:Q5398426 wd:Q526877 }
  ?other wdt:P31/wdt:P279* ?type.
}`);
const ambiguous = [...new Set(collisions.map(row => normalize(row.title.value)))].sort();
if (ambiguous.length < 50) throw new Error("Collision data unexpectedly small; keeping the previous snapshot.");
const catalog = {
  updated: new Date().toISOString().slice(0, 10),
  source: "https://www.wikidata.org/",
  queryEndpoint: endpoint,
  license: "CC0-1.0",
  works: works.size,
  ambiguous,
  titles: Object.fromEntries([...entries].sort(([a], [b]) => a.localeCompare(b, "en"))
    .map(([title, years]) => [title, [...years].sort()]))
};
// Finish every request and validate before replacing the bundled file.
const temporary = new URL(`../.catalog-${process.pid}.tmp`, import.meta.url);
try {
  await writeFile(temporary,
    `// Generated by npm run catalog:update. Wikidata structured data: CC0.\nconst INDIAN_CATALOG = ${JSON.stringify(catalog)};\n`);
  await rename(temporary, new URL("../catalog.js", import.meta.url));
} finally {
  await rm(temporary, { force: true });
}
console.log(`Saved ${catalog.works} works, ${entries.size} names, ${ambiguous.length} ambiguous names.`);
